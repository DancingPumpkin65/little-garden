"""Build transparent, cropped frame sheets with source WebP timing for Godot."""
from pathlib import Path
from PIL import Image
import math

SOURCE = Path('assets/stickers/source')
OUTPUT = SOURCE.parent / 'frames'
OUTPUT.mkdir(exist_ok=True)
ALIASES = {'butterflies': 'butterfliies', 'mmouse': 'mouse'}
NAMES = 'myhead ok overworked hihi hem dfaar pat actingcute mouse walking coffee emmm chincrying butterflies really alone mkhassma noice flouss'.split()
CELL = 128
library = ['# Generated by art/stickers/build_stickers.py. Keep original files as sources.', 'class_name GardenStickerLibrary', 'extends RefCounted', '', 'const CLIPS: Dictionary[String, SpriteFrames] = {']
for name in NAMES:
    path = SOURCE / (ALIASES.get(name, name) + '.webp')
    source = Image.open(path)
    frames, durations = [], []
    bounds = None
    for i in range(getattr(source, 'n_frames', 1)):
        source.seek(i)
        frame = source.convert('RGBA').copy()
        box = frame.getbbox()
        if box:
            bounds = box if bounds is None else (min(bounds[0],box[0]),min(bounds[1],box[1]),max(bounds[2],box[2]),max(bounds[3],box[3]))
        frames.append(frame)
        durations.append(max(0.01,source.info.get('duration',100)/1000))
    bounds = bounds or (0,0,source.width,source.height)
    columns = min(8,len(frames))
    sheet = Image.new('RGBA',(columns*CELL,math.ceil(len(frames)/columns)*CELL))
    for i, frame in enumerate(frames):
        frame = frame.crop(bounds)
        frame.thumbnail((CELL-4,CELL-4),Image.Resampling.LANCZOS)
        sheet.alpha_composite(frame,((i%columns)*CELL+(CELL-frame.width)//2,(i//columns)*CELL+(CELL-frame.height)//2))
    sheet.save(OUTPUT/(name+'.png'))
    resource = [f'[gd_resource type="SpriteFrames" load_steps={len(frames)+2} format=3]', '', f'[ext_resource type="Texture2D" path="res://assets/stickers/frames/{name}.png" id="1"]']
    for i in range(len(frames)):
        resource += ['',f'[sub_resource type="AtlasTexture" id="Frame_{i}"]','atlas = ExtResource("1")',f'region = Rect2({(i%columns)*CELL}, {(i//columns)*CELL}, {CELL}, {CELL})']
    items = ',\n'.join('{"duration": %.4f, "texture": SubResource("Frame_%d")}'%(duration,i) for i,duration in enumerate(durations))
    resource += ['', '[resource]', 'animations = [{"frames": ['+items+'], "loop": true, "name": &"default", "speed": 1.0}]']
    (OUTPUT/(name+'.tres')).write_text('\n'.join(resource)+'\n',encoding='utf-8')
    library.append(f'\t"{name}": preload("res://assets/stickers/frames/{name}.tres"),')
    print(name,len(frames),'frames',round(sum(durations),2),'seconds')
library.append('}')
Path('scripts/sticker_library.gd').write_text('\n'.join(library)+'\n',encoding='utf-8')
